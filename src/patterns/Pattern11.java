package patterns;

public class Pattern11 {
    public static void main(String[] args) {

        int z=1;
        for(int i=1;i<6;i++){
            for (int k=0;k<i;k++){
                System.out.print(z);
                System.out.print(" ");
                z++;
            }
            System.out.println(" ");

        }

    }
}
